/**
 * Unified Professional Excel (.xlsx) Generator (Part C)
 * Built with ExcelJS, embedded official PNG school emblem, styled merged headers,
 * frozen table header rows, zebra striping, currency/date number formatting,
 * formula-based totals, and landscape print setups.
 */

import ExcelJS from 'exceljs';
import { getSchoolLogoBuffer } from '../config/logo.js';

export interface ExcelColumnDef {
  header: string;
  key: string;
  width?: number;
  type?: 'string' | 'number' | 'currency' | 'date';
  align?: 'left' | 'center' | 'right';
}

export interface ExcelReportOptions {
  school: {
    name: string;
    tagline?: string;
    address: string;
    phone: string;
    email: string;
    affiliationNumber?: string;
    logoUrl?: string | null;
  };
  title: string;
  sheetName?: string;
  sessionName?: string;
  filtersSummary?: string;
  generatedBy?: string;
  columns: ExcelColumnDef[];
  rows: Array<Record<string, any>>;
  summaryMetrics?: Array<{ label: string; value: string | number }>;
  totalColumns?: string[]; // Keys of columns that should have SUM formula at the bottom
}

export async function generateStyledExcelReport(options: ExcelReportOptions): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = options.school.name;
  workbook.lastModifiedBy = options.generatedBy || 'PBPS Administrator';
  workbook.created = new Date();
  workbook.modified = new Date();

  const ws = workbook.addWorksheet(options.sheetName || 'Report', {
    views: [{ showGridLines: true }],
    pageSetup: {
      paperSize: 9, // A4
      orientation: 'landscape',
      fitToPage: true,
      fitToWidth: 1,
      fitToHeight: 0,
      margins: {
        left: 0.5,
        right: 0.5,
        top: 0.75,
        bottom: 0.75,
        header: 0.3,
        footer: 0.3
      }
    },
    headerFooter: {
      oddFooter: `&L${options.school.name} - ${options.title}&RPage &P of &N`
    }
  });

  const numCols = Math.max(options.columns.length, 6);
  const endColLetter = String.fromCharCode(64 + numCols);

  // 1. Embed School Logo if available
  const logoBuf = getSchoolLogoBuffer(options.school.logoUrl);
  if (logoBuf && logoBuf.length > 0) {
    try {
      const imageId = workbook.addImage({
        buffer: logoBuf,
        extension: 'png'
      });
      // Place in cells A1 to B3
      ws.addImage(imageId, {
        tl: { col: 0.2, row: 0.2 },
        ext: { width: 68, height: 68 }
      });
    } catch (err) {
      console.warn('[Excel] Failed embedding logo image in workbook:', err);
    }
  }

  // 2. Title Block
  // Row 1: School Name (Merged across columns)
  ws.mergeCells(`B1:${endColLetter}1`);
  const r1 = ws.getCell('B1');
  r1.value = options.school.name.toUpperCase();
  r1.font = { name: 'Calibri', size: 16, bold: true, color: { argb: 'FF1E1B4B' } };
  r1.alignment = { vertical: 'middle', horizontal: 'center' };
  ws.getRow(1).height = 26;

  // Row 2: Tagline / Address / Affiliation
  ws.mergeCells(`B2:${endColLetter}2`);
  const r2 = ws.getCell('B2');
  r2.value = `${options.school.address} | Phone: ${options.school.phone} | Affiliation No: ${options.school.affiliationNumber || 'PBPS-8491'}`;
  r2.font = { name: 'Calibri', size: 9, italic: true, color: { argb: 'FF475569' } };
  r2.alignment = { vertical: 'middle', horizontal: 'center' };
  ws.getRow(2).height = 18;

  // Row 3: Report Title
  ws.mergeCells(`A3:${endColLetter}3`);
  const r3 = ws.getCell('A3');
  r3.value = options.title.toUpperCase();
  r3.font = { name: 'Calibri', size: 12, bold: true, color: { argb: 'FF1E293B' } };
  r3.fill = {
    type: 'pattern',
    pattern: 'solid',
    fgColor: { argb: 'FFF1F5F9' }
  };
  r3.alignment = { vertical: 'middle', horizontal: 'center' };
  ws.getRow(3).height = 22;

  // Row 4: Meta info (Session, Filters, Generated On, Officer)
  ws.mergeCells(`A4:${endColLetter}4`);
  const r4 = ws.getCell('A4');
  const metaParts = [
    options.sessionName ? `Academic Session: ${options.sessionName}` : '',
    options.filtersSummary ? `Filter: ${options.filtersSummary}` : '',
    `Generated On: ${new Date().toLocaleString('en-IN')}`,
    options.generatedBy ? `Generated By: ${options.generatedBy}` : ''
  ].filter(Boolean).join('   |   ');
  r4.value = metaParts;
  r4.font = { name: 'Calibri', size: 9, bold: false, color: { argb: 'FF64748B' } };
  r4.alignment = { vertical: 'middle', horizontal: 'center' };
  ws.getRow(4).height = 18;

  let currentRowIdx = 5;

  // Row 5: KPI Summary Metrics (if provided)
  if (options.summaryMetrics && options.summaryMetrics.length > 0) {
    currentRowIdx = 6;
    let metricCol = 1;
    options.summaryMetrics.forEach(m => {
      const cell = ws.getCell(currentRowIdx, metricCol);
      cell.value = `${m.label}: ${m.value}`;
      cell.font = { name: 'Calibri', size: 9, bold: true, color: { argb: 'FF1E1B4B' } };
      cell.fill = {
        type: 'pattern',
        pattern: 'solid',
        fgColor: { argb: 'FFE0E7FF' }
      };
      cell.alignment = { vertical: 'middle', horizontal: 'center' };
      cell.border = {
        top: { style: 'thin', color: { argb: 'FFC7D2FE' } },
        bottom: { style: 'thin', color: { argb: 'FFC7D2FE' } },
        left: { style: 'thin', color: { argb: 'FFC7D2FE' } },
        right: { style: 'thin', color: { argb: 'FFC7D2FE' } }
      };
      metricCol += 2;
    });
    ws.getRow(currentRowIdx).height = 20;
    currentRowIdx += 2;
  } else {
    currentRowIdx = 6;
  }

  // 3. Table Header Row
  const headerRowIdx = currentRowIdx;
  const headerRow = ws.getRow(headerRowIdx);
  headerRow.height = 26;

  options.columns.forEach((col, idx) => {
    const colNum = idx + 1;
    const cell = headerRow.getCell(colNum);
    cell.value = col.header;
    cell.font = { name: 'Calibri', size: 10, bold: true, color: { argb: 'FFFFFFFF' } };
    cell.fill = {
      type: 'pattern',
      pattern: 'solid',
      fgColor: { argb: 'FF1E1B4B' } // Royal Navy Brand
    };
    cell.alignment = {
      vertical: 'middle',
      horizontal: col.align || (col.type === 'number' || col.type === 'currency' ? 'right' : 'left'),
      wrapText: true
    };
    cell.border = {
      top: { style: 'medium', color: { argb: 'FF0F172A' } },
      bottom: { style: 'medium', color: { argb: 'FF0F172A' } },
      left: { style: 'thin', color: { argb: 'FF334155' } },
      right: { style: 'thin', color: { argb: 'FF334155' } }
    };
  });

  // Freeze Header & Set Repeat Titles on Print
  ws.views = [{ state: 'frozen', ySplit: headerRowIdx }];
  ws.pageSetup.printTitlesRow = `${headerRowIdx}:${headerRowIdx}`;

  // 4. Data Rows
  let dataStartRow = headerRowIdx + 1;
  options.rows.forEach((rowData, rIdx) => {
    const rowNum = dataStartRow + rIdx;
    const row = ws.getRow(rowNum);
    row.height = 20;
    const isEven = rIdx % 2 === 0;

    options.columns.forEach((col, cIdx) => {
      const colNum = cIdx + 1;
      const cell = row.getCell(colNum);
      const rawVal = rowData[col.key];

      if (col.type === 'currency' || col.type === 'number') {
        const numVal = Number(rawVal);
        cell.value = isNaN(numVal) ? 0 : numVal;
        cell.numFmt = col.type === 'currency' ? '₹#,##0.00;[Red](₹#,##0.00);"-"' : '#,##0.00';
      } else if (col.type === 'date' && rawVal) {
        const d = new Date(rawVal);
        if (!isNaN(d.getTime())) {
          cell.value = d;
          cell.numFmt = 'DD-MM-YYYY';
        } else {
          cell.value = String(rawVal);
        }
      } else {
        cell.value = rawVal === null || rawVal === undefined ? '' : String(rawVal);
      }

      cell.font = { name: 'Calibri', size: 9.5, color: { argb: 'FF1E293B' } };
      cell.alignment = {
        vertical: 'middle',
        horizontal: col.align || (col.type === 'number' || col.type === 'currency' ? 'right' : 'left')
      };

      if (!isEven) {
        cell.fill = {
          type: 'pattern',
          pattern: 'solid',
          fgColor: { argb: 'FFF8FAFC' }
        };
      }

      cell.border = {
        top: { style: 'thin', color: { argb: 'FFE2E8F0' } },
        bottom: { style: 'thin', color: { argb: 'FFE2E8F0' } },
        left: { style: 'thin', color: { argb: 'FFE2E8F0' } },
        right: { style: 'thin', color: { argb: 'FFE2E8F0' } }
      };
    });
  });

  const lastDataRow = dataStartRow + options.rows.length - 1;

  // 5. Formula Totals Row (if rows exist)
  if (options.rows.length > 0 && options.totalColumns && options.totalColumns.length > 0) {
    const totalRowIdx = lastDataRow + 1;
    const totalRow = ws.getRow(totalRowIdx);
    totalRow.height = 24;

    options.columns.forEach((col, cIdx) => {
      const colNum = cIdx + 1;
      const colLetter = String.fromCharCode(64 + colNum);
      const cell = totalRow.getCell(colNum);

      if (cIdx === 0) {
        cell.value = 'GRAND TOTAL';
        cell.font = { name: 'Calibri', size: 10, bold: true, color: { argb: 'FF0F172A' } };
        cell.alignment = { vertical: 'middle', horizontal: 'left' };
      } else if (options.totalColumns?.includes(col.key)) {
        cell.value = {
          formula: `SUM(${colLetter}${dataStartRow}:${colLetter}${lastDataRow})`
        };
        cell.numFmt = col.type === 'currency' ? '₹#,##0.00' : '#,##0.00';
        cell.font = { name: 'Calibri', size: 10, bold: true, color: { argb: 'FF0F172A' } };
        cell.alignment = { vertical: 'middle', horizontal: 'right' };
      }

      cell.fill = {
        type: 'pattern',
        pattern: 'solid',
        fgColor: { argb: 'FFE2E8F0' }
      };
      cell.border = {
        top: { style: 'thin', color: { argb: 'FF0F172A' } },
        bottom: { style: 'double', color: { argb: 'FF0F172A' } },
        left: { style: 'thin', color: { argb: 'FFCBD5E1' } },
        right: { style: 'thin', color: { argb: 'FFCBD5E1' } }
      };
    });
  }

  // 6. Set auto-fitted column widths with padding
  options.columns.forEach((col, idx) => {
    const colNum = idx + 1;
    let maxLen = col.header.length;
    options.rows.forEach(r => {
      const v = r[col.key];
      if (v !== undefined && v !== null) {
        const s = String(v);
        if (s.length > maxLen) maxLen = s.length;
      }
    });
    ws.getColumn(colNum).width = Math.max(col.width || 12, Math.min(maxLen + 4, 38));
  });

  // Enable AutoFilter over headers & data
  ws.autoFilter = {
    from: { row: headerRowIdx, column: 1 },
    to: { row: Math.max(lastDataRow, headerRowIdx), column: options.columns.length }
  };

  const uint8 = await workbook.xlsx.writeBuffer();
  return Buffer.from(uint8);
}
